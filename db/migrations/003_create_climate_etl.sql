CREATE ROLE climate_etl LOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

GRANT CONNECT ON DATABASE klimahistorie TO climate_etl;
GRANT USAGE ON SCHEMA public TO climate_etl;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO climate_etl;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE ON TABLES TO climate_etl;

-- Sequence access is needed for future identity/serial columns.
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO climate_etl;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
    GRANT USAGE ON SEQUENCES TO climate_etl;
